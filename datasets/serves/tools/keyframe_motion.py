"""Turn hand-keyed serve poses into the same motion file a captured serve makes.

    python3 -I datasets/serves/tools/keyframe_motion.py alcaraz

Reads datasets/serves/<player>/keyframes.json (key poses with times, written from video and coaching analysis)
and writes src/serve/motion/<player>-serve.js:  window.SERVE_MOTIONS.<player> = { first, second }.
Same format as export_motion.py (body heights, seen from behind, x + = the player's right, y = height), so the
game plays it exactly like Sinner's captured serve. Frames are sampled at 30 fps on a Catmull-Rom curve through
the keys, so the motion flows instead of snapping between poses.

When real clips of the player are captured (pose.swift → clean_keypoints.py → export_motion.py), the captured
motion replaces this one. Owner: Serve Analyst.
"""
import json, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))))
FPS = 30

def sample(keys, t):
    n = len(keys)
    if t <= keys[0]["t"]: return keys[0]["j"]
    if t >= keys[-1]["t"]: return keys[-1]["j"]
    k = 0
    while t > keys[k + 1]["t"]: k += 1
    u = (t - keys[k]["t"]) / (keys[k + 1]["t"] - keys[k]["t"])
    P = [keys[max(0, k - 1)]["j"], keys[k]["j"], keys[k + 1]["j"], keys[min(n - 1, k + 2)]["j"]]
    cr = lambda a, b, c, d: 0.5 * (2 * b + (c - a) * u + (2 * a - 5 * b + 4 * c - d) * u * u + (3 * b - a - 3 * c + d) * u ** 3)
    return {j: [round(cr(*(p[j][0] for p in P)), 3), round(cr(*(p[j][1] for p in P)), 3)] for j in keys[k]["j"]}

def build(spec, src):
    keys = spec["keys"]
    frames, t, i = [], 0.0, 0
    while t <= keys[-1]["t"] + 1e-9:
        frames.append({"i": i, "t": round(t, 3), "j": sample(keys, t)}); t += 1 / FPS; i += 1
    return {"player": src["player"], "source": "keyframes (" + src["status"] + ")", "note": spec["note"], "timeScale": 1.0,
            "units": src["units"], "events": spec["events"], "keys": [{"t": k["t"], "label": k["label"]} for k in keys], "frames": frames}

def load(player, which=("first", "second")):
    src = json.load(open(os.path.join(ROOT, "datasets/serves", player, "keyframes.json")))
    return {n: build(src[n], src) for n in which if n in src}, src

if __name__ == "__main__":
  player = sys.argv[1] if len(sys.argv) > 1 else "alcaraz"
  out, src = load(player)
  OUT = os.path.join(ROOT, f"src/serve/motion/{player}-serve.js")
  with open(OUT, "w") as f:
      f.write(f"// Generated by datasets/serves/tools/keyframe_motion.py from datasets/serves/{player}/keyframes.json.\n"
              f"// {src['status']}. Do not edit by hand: change the keyframes and re-run. Owner: Serve Analyst.\n"
              "window.SERVE_MOTIONS = window.SERVE_MOTIONS || {};\n"
              f"window.SERVE_MOTIONS.{player} = {json.dumps(out, separators=(',', ':'))};\n")
  for n, m in out.items():
      print(f"{n:6s}: {len(m['frames'])} frames, events {m['events']}")
  print(f"wrote {os.path.relpath(OUT, ROOT)} ({os.path.getsize(OUT) // 1024} KB)")
