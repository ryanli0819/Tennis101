"""Turn a cleaned serve clip into a game motion file the character can play.

    python3 -I datasets/serves/tools/export_motion.py

Reads  datasets/serves/sinner/front.keypoints.json  (the 'clean' joints)
Writes src/serve/motion/sinner-serve.js              (window.SERVE_MOTIONS.sinner.first)

Coordinates in the output are in BODY HEIGHTS, so the same motion fits any player's real height:
  x = sideways from the hips, + = the player's right   (the front-view video is mirrored, because
      in the game we see Sinner from behind)
  y = height above the ground
The camera zoom and Sinner jumping toward the camera are removed with the per-frame body scale.
Missing joints hold their last known position relative to the hips, so the figure never loses a limb.
"""
import json, os

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))))
SRC = os.path.join(ROOT, "datasets/serves/sinner/front.keypoints.json")
OUT = os.path.join(ROOT, "src/serve/motion/sinner-serve.js")
JOINTS = ["nose", "neck", "leftShoulder", "rightShoulder", "leftElbow", "rightElbow", "leftWrist", "rightWrist",
          "root", "leftHip", "rightHip", "leftKnee", "rightKnee", "leftAnkle", "rightAnkle"]
# Serve events (frame numbers), read off the 20 key frames. The Serve Analyst can refine these.
EVENTS = {"start": 46, "tossRelease": 55, "trophy": 66, "contact": 74, "finish": 88}

d = json.load(open(SRC))
W, H = d["width"], d["height"]
F = d["frames"]
px = lambda v: (v[0] * W, v[1] * H)                       # normalized -> pixels (keeps the aspect right)

# Body height in pixels, from the calm setup frames: nose-to-ankle is about 90% of full height.
spans = []
for f in F[:EVENTS["start"]]:
    c = f["clean"]
    if "nose" in c and "leftAnkle" in c and "rightAnkle" in c:
        spans.append((px(c["leftAnkle"])[1] + px(c["rightAnkle"])[1]) / 2 - px(c["nose"])[1])
spans.sort()
BODY = spans[len(spans) // 2] / 0.90
ROOT_UP0 = None                                            # hip height above the ground, setup frames

frames, last_rel, root_y0 = [], {}, None
for f in F:
    c, s = f["clean"], f.get("scale", 1.0) or 1.0
    if "root" not in c: continue
    rx, ry = px(c["root"])
    if root_y0 is None:
        ankles = [px(c[a])[1] for a in ("leftAnkle", "rightAnkle") if a in c]
        root_y0 = ry; ROOT_UP0 = (max(ankles) - ry) / BODY if ankles else 0.5
    # hips rise when he jumps; moving toward the camera also moves him down the image, so this is approximate
    root_up = max(0.35, ROOT_UP0 + (root_y0 - ry) / (BODY * s) * 0.6)
    rel = {}
    for j in JOINTS:
        if j in c:
            x, y = px(c[j])
            rel[j] = (-(x - rx) / (BODY * s), (ry - y) / (BODY * s))   # mirrored: seen from behind
        elif j in last_rel:
            rel[j] = last_rel[j]                                        # hold the last known pose
    last_rel.update(rel)
    frames.append({"i": f["i"], "t": round(f["t"], 3),
                   "j": {k: [round(v[0], 3), round(v[1] + root_up, 3)] for k, v in rel.items()}})

# Joints first seen later in the clip: back-fill the early frames with their first known position.
for j in JOINTS:
    first = next((fr["j"][j] for fr in frames if j in fr["j"]), None)
    for fr in frames:
        if j in fr["j"]: break
        if first: fr["j"][j] = first

t_of = {fr["i"]: fr["t"] for fr in frames}
motion = {
    "player": "sinner", "serve": "first", "source": "datasets/serves/sinner/front.keypoints.json (clean)",
    "units": "body heights; x + = player's right, y = above the ground; seen from behind",
    "events": {k: t_of[v] for k, v in EVENTS.items()},
    "frames": frames,
}
os.makedirs(os.path.dirname(OUT), exist_ok=True)
with open(OUT, "w") as out:
    out.write("// Generated by datasets/serves/tools/export_motion.py from Sinner's real serve (front video, cleaned).\n"
              "// Do not edit by hand: change the data or the script and re-run it. Owner: Serve Analyst.\n"
              "window.SERVE_MOTIONS = window.SERVE_MOTIONS || {};\n"
              "window.SERVE_MOTIONS.sinner = window.SERVE_MOTIONS.sinner || {};\n"
              f"window.SERVE_MOTIONS.sinner.first = {json.dumps(motion, separators=(',', ':'))};\n")
print(f"wrote {os.path.relpath(OUT, ROOT)}: {len(frames)} frames, events {motion['events']}, "
      f"{os.path.getsize(OUT) // 1024} KB, hip height {ROOT_UP0:.2f} body heights")
