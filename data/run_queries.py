"""Run every data/queries/*.sql against data/tennis101.sqlite and write data/query_results.md.

    python3 -I data/run_queries.py
"""
import os, sqlite3, glob

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
db = sqlite3.connect(os.path.join(ROOT, "data", "tennis101.sqlite"))
out = ["# Query results", "", "Generated by `data/run_queries.py` from `data/tennis101.sqlite`. Rebuild with `data/build_db.py` first.", ""]
for f in sorted(glob.glob(os.path.join(ROOT, "data", "queries", "*.sql"))):
    sql = open(f).read()
    title = sql.splitlines()[0].lstrip("- ").strip()
    cur = db.execute(sql)
    cols = [c[0] for c in cur.description]
    rows = cur.fetchall()
    out += [f"## {title}", f"`data/queries/{os.path.basename(f)}`", "",
            "| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    out += ["| " + " | ".join("" if v is None else str(v) for v in r) + " |" for r in rows]
    out.append("")
open(os.path.join(ROOT, "data", "query_results.md"), "w").write("\n".join(out))
print("\n".join(out))
